import { useEffect, useRef, useState } from 'react';
import Zephlo from 'zephlo';
import type { ZephloInstance } from 'zephlo';
import { getAppConfig, getWidgetApiUrl } from '../lib/appConfig';
import { useEmitAssistantContext } from '../assistant/context';
import AgentToolsRegistrar from '../assistant/registrars/AgentToolsRegistrar';
import AccountToolsRegistrar from '../assistant/registrars/AccountToolsRegistrar';
import NavigationToolsRegistrar from '../assistant/registrars/NavigationToolsRegistrar';
import KnowledgeToolsRegistrar from '../assistant/registrars/KnowledgeToolsRegistrar';
import WidgetToolsRegistrar from '../assistant/registrars/WidgetToolsRegistrar';
import PromptToolsRegistrar from '../assistant/registrars/PromptToolsRegistrar';
import McpToolsRegistrar from '../assistant/registrars/McpToolsRegistrar';
import ConversationToolsRegistrar from '../assistant/registrars/ConversationToolsRegistrar';
import LeadToolsRegistrar from '../assistant/registrars/LeadToolsRegistrar';
import AnalyticsToolsRegistrar from '../assistant/registrars/AnalyticsToolsRegistrar';
import OrgToolsRegistrar from '../assistant/registrars/OrgToolsRegistrar';

// ---------------------------------------------------------------------------
// DashboardAssistant
// Initialises the Zephlo widget via the npm package, mounts the floating
// action button, and hosts the registrar stack — one component per domain
// that registers the tools for that domain by delegating to the matching
// React Query hooks. This guarantees the agent path and the UI path run
// the same logic (validation, cache invalidation, side effects).
//
// Config is injected at runtime via /config.js (generated by
// docker-entrypoint.sh). Set ASSISTANT_CHATBOT_ID and ASSISTANT_API_KEY
// as env vars on the container.
// ---------------------------------------------------------------------------

function DashboardAssistant() {
  const instanceRef = useRef<ZephloInstance | null>(null);
  const [instance, setInstance] = useState<ZephloInstance | null>(null);

  useEffect(() => {
    const config = getAppConfig();
    const CHATBOT_ID = config.ASSISTANT_CHATBOT_ID;
    const API_KEY = config.ASSISTANT_API_KEY;

    if (!CHATBOT_ID || !API_KEY) return;

    const apiUrl = getWidgetApiUrl();
    const z = Zephlo.initialize({
      key: API_KEY,
      chatbotId: CHATBOT_ID,
      ...(apiUrl ? { apiUrl } : {}),
    });

    // Zephlo.initialize only configures the shared core — place a <zephlo-fab>
    // on the page so the floating button shows.
    let fabEl = document.querySelector('zephlo-fab');
    if (!fabEl) {
      fabEl = document.createElement('zephlo-fab');
      document.body.appendChild(fabEl);
    }

    instanceRef.current = z;
    setInstance(z);

    (window as any).DashboardAssistant = {
      tools: () => z.webMcpTools(),
    };

    return () => {
      z.destroy();
      document.querySelector('zephlo-fab')?.remove();
      instanceRef.current = null;
      setInstance(null);
      delete (window as any).DashboardAssistant;
    };
  }, []);

  // Forward AssistantContext snapshots to the agent via WebSocket context_update.
  useEmitAssistantContext(
    instance ? (payload) => instance.sendContextUpdate(payload) : null,
  );

  // The registrars need a live Zephlo instance to register tools.
  // Mount them only after init; each unmount path unregisters via destroy().
  if (!instance) return null;

  return (
    <>
      <AgentToolsRegistrar instance={instance} />
      <AccountToolsRegistrar instance={instance} />
      <NavigationToolsRegistrar instance={instance} />
      <KnowledgeToolsRegistrar instance={instance} />
      <WidgetToolsRegistrar instance={instance} />
      <PromptToolsRegistrar instance={instance} />
      <McpToolsRegistrar instance={instance} />
      <ConversationToolsRegistrar instance={instance} />
      <LeadToolsRegistrar instance={instance} />
      <AnalyticsToolsRegistrar instance={instance} />
      <OrgToolsRegistrar instance={instance} />
    </>
  );
}

export default DashboardAssistant;
