import { useEffect, useRef } from 'react';
import { useNavigate } from 'react-router-dom';
import { useQueryClient } from '@tanstack/react-query';
import Flunkie from '@flunkie/flunkie';
import type { FlunkieInstance } from '@flunkie/flunkie';
import * as chatbotApi from '../api/chatbots';

// ---------------------------------------------------------------------------
// DashboardAssistant
// Initialises the Flunkie widget via the npm package and registers dashboard
// tools so the agent can help users manage their agents from the dashboard.
//
// All tools delegate to the shared chatbot API service (api/chatbots.ts)
// so business logic lives in one place.
//
// Config is injected at runtime via /config.js (generated by docker-entrypoint.sh).
// Set ASSISTANT_CHATBOT_ID and ASSISTANT_API_KEY as env vars on the container.
// ---------------------------------------------------------------------------

interface AppConfig {
  ASSISTANT_CHATBOT_ID?: string;
  ASSISTANT_API_KEY?: string;
}

function getConfig(): AppConfig {
  return (window as any).__APP_CONFIG__ || {};
}

const showUserProp = {
  show_user: {
    type: 'boolean',
    description: 'If true, navigate the user to see the result in the dashboard',
  },
} as const;

function DashboardAssistant() {
  const navigate = useNavigate();
  const queryClient = useQueryClient();
  const instanceRef = useRef<FlunkieInstance | null>(null);

  useEffect(() => {
    const config = getConfig();
    const CHATBOT_ID = config.ASSISTANT_CHATBOT_ID;
    const API_KEY = config.ASSISTANT_API_KEY;

    if (!CHATBOT_ID || !API_KEY) return;

    const instance = Flunkie.initialize({
      key: API_KEY,
      chatbotId: CHATBOT_ID,
    });

    instanceRef.current = instance;
    registerTools(instance);

    (window as any).DashboardAssistant = {
      tools: () => instance.webMcpTools(),
    };

    return () => {
      instance.destroy();
      instanceRef.current = null;
      delete (window as any).DashboardAssistant;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  function registerTools(agent: FlunkieInstance) {
    // ---- list_chatbots ----
    agent.registerTool({
      name: 'list_chatbots',
      description: 'List all agents for the current user. Returns name, id, status, and website URL for each.',
      inputSchema: {
        type: 'object',
        properties: { ...showUserProp },
      },
      execute: async (params) => {
        const chatbots = await chatbotApi.listChatbots();
        if (params.show_user) navigate('/dashboard');
        if (chatbots.length === 0) return 'No agents found. The user can create one.';
        return chatbots
          .map((c) => `- ${c.name} (ID: ${c.id}, uuid: ${c.public_id}, status: ${c.status}${c.website_url ? `, url: ${c.website_url}` : ''})`)
          .join('\n');
      },
    });

    // ---- get_chatbot_details ----
    agent.registerTool({
      name: 'get_chatbot_details',
      description: 'Get full details of a specific agent by its ID, including crawl jobs, widget settings, and MCP servers.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID' },
          ...showUserProp,
        },
        required: ['chatbot_id'],
      },
      execute: async (params) => {
        const chatbot = await chatbotApi.getChatbot(params.chatbot_id as string);
        if (params.show_user) navigate(`/agents/${params.chatbot_id}?section=overview`);
        return JSON.stringify(chatbot, null, 2);
      },
    });

    // ---- create_chatbot ----
    agent.registerTool({
      name: 'create_chatbot',
      description: 'Create a new agent. Only a name is required.',
      inputSchema: {
        type: 'object',
        properties: {
          name: { type: 'string', description: 'Name for the new agent' },
          ...showUserProp,
        },
        required: ['name'],
      },
      execute: async (params) => {
        const chatbot = await chatbotApi.createChatbot({ name: params.name as string });
        queryClient.invalidateQueries({ queryKey: ['chatbots'] });
        if (params.show_user) navigate(`/agents/${chatbot.public_id}`);
        return JSON.stringify({ id: chatbot.id, name: chatbot.name, status: chatbot.status });
      },
    });

    // ---- update_chatbot ----
    agent.registerTool({
      name: 'update_chatbot',
      description: 'Update an agent name, description, or custom instructions.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID to update' },
          name: { type: 'string', description: 'New name (optional)' },
          description: { type: 'string', description: 'New description (optional)' },
          instructions: { type: 'string', description: 'Custom instructions for the AI (optional)' },
          ...showUserProp,
        },
        required: ['chatbot_id'],
      },
      execute: async (params) => {
        const chatbotId = params.chatbot_id as string;
        const current = await chatbotApi.getChatbot(chatbotId);
        const data = {
          name: (params.name as string) || current.name,
          description: params.description !== undefined ? (params.description as string) : current.description,
          instructions: params.instructions !== undefined ? (params.instructions as string) : current.instructions,
        };
        await chatbotApi.updateChatbot(chatbotId, data);
        queryClient.invalidateQueries({ queryKey: ['chatbots', chatbotId] });
        queryClient.invalidateQueries({ queryKey: ['chatbots'] });
        if (params.show_user) navigate(`/agents/${chatbotId}?section=details`);
        return JSON.stringify({ id: chatbotId, ...data });
      },
    });

    // ---- delete_chatbot ----
    agent.registerTool({
      name: 'delete_chatbot',
      description: 'Delete an agent by its ID. This is irreversible — always confirm with the user first.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID to delete' },
          ...showUserProp,
        },
        required: ['chatbot_id'],
      },
      execute: async (params) => {
        await chatbotApi.deleteChatbot(params.chatbot_id as string);
        queryClient.invalidateQueries({ queryKey: ['chatbots'] });
        if (params.show_user) navigate('/dashboard');
        return `Deleted agent ${params.chatbot_id}.`;
      },
    });

    // ---- navigate_to ----
    agent.registerTool({
      name: 'navigate_to',
      description: [
        'Navigate the user to a page in the dashboard.',
        'Available routes:',
        '  /dashboard - Home page with all agents',
        '  /agents/new - Create a new agent',
        '  /agents/{id} - Agent detail page (general info)',
        '  /agents/{id}?section=overview - Overview with status, embed code, API keys',
        '  /agents/{id}?section=knowledge - Knowledge / crawl settings',
        '  /agents/{id}?section=config - Widget configuration',
        '  /agents/{id}?section=tools - MCP server tools',
        '  /agents/{id}/chat - Chat preview / test',
      ].join('\n'),
      inputSchema: {
        type: 'object',
        properties: {
          path: { type: 'string', description: 'The route path to navigate to, e.g. /agents/abc123?section=config' },
        },
        required: ['path'],
      },
      execute: (params) => {
        const path = params.path as string;
        navigate(path);
        return `Navigated to ${path}`;
      },
    });

    // ---- discover_pages ----
    agent.registerTool({
      name: 'discover_pages',
      description: 'Discover all pages on a website without crawling them. Returns a list of URLs found.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID' },
          website_url: { type: 'string', description: 'The website URL to discover pages from' },
          ...showUserProp,
        },
        required: ['chatbot_id', 'website_url'],
      },
      execute: async (params) => {
        const result = await chatbotApi.discoverUrls(params.chatbot_id as string, params.website_url as string);
        const urls = result.urls.map((u) => u.url);
        if (params.show_user) navigate(`/agents/${params.chatbot_id}?section=knowledge`);
        return JSON.stringify({ count: urls.length, urls });
      },
    });

    // ---- crawl_pages ----
    agent.registerTool({
      name: 'crawl_pages',
      description: 'Start crawling specific URLs (or all discovered URLs) to index content for an agent.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID' },
          website_url: { type: 'string', description: 'The website URL — discovers and crawls all pages' },
          selected_urls: {
            type: 'array',
            items: { type: 'string' },
            description: 'Specific URLs to crawl (optional — if omitted, discovers all pages first)',
          },
          ...showUserProp,
        },
        required: ['chatbot_id'],
      },
      execute: async (params) => {
        const chatbotId = params.chatbot_id as string;
        let urls = params.selected_urls as string[] | undefined;

        if (!urls || urls.length === 0) {
          const discovered = await chatbotApi.discoverUrls(chatbotId, params.website_url as string);
          urls = discovered.urls.map((u) => u.url);
        }

        const job = await chatbotApi.startCrawl(chatbotId, urls);
        queryClient.invalidateQueries({ queryKey: ['chatbots', chatbotId] });
        if (params.show_user) navigate(`/agents/${chatbotId}?section=knowledge`);
        return JSON.stringify({ job_id: job.id, pages_count: urls.length });
      },
    });

    // ---- get_crawl_status ----
    agent.registerTool({
      name: 'get_crawl_status',
      description: 'Get the status of a crawl job for an agent.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID to check crawl status for' },
          ...showUserProp,
        },
        required: ['chatbot_id'],
      },
      execute: async (params) => {
        const chatbot = await chatbotApi.getChatbot(params.chatbot_id as string);
        const jobs = chatbot.crawl_jobs || [];
        if (params.show_user) navigate(`/agents/${params.chatbot_id}?section=knowledge`);
        if (jobs.length === 0) return 'No crawl jobs found for this agent.';
        return JSON.stringify(
          jobs.map((j) => ({
            id: j.id,
            status: j.status,
            pages_crawled: j.pages_crawled,
            started_at: j.started_at,
          }))
        );
      },
    });

    // ---- create_api_key ----
    agent.registerTool({
      name: 'create_api_key',
      description: 'Create a new API key for an agent. The full key is only shown once.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID' },
          name: { type: 'string', description: 'A name for this API key (e.g. "Production")' },
          ...showUserProp,
        },
        required: ['chatbot_id', 'name'],
      },
      execute: async (params) => {
        const key = await chatbotApi.createApiKey(params.chatbot_id as string, params.name as string);
        await navigator.clipboard.writeText(key.key);
        if (params.show_user) navigate(`/agents/${params.chatbot_id}?section=overview`);
        return `Created API key "${key.name}" and copied it to the user's clipboard. This is the only time the full key is available.`;
      },
    });

    // ---- list_api_keys ----
    agent.registerTool({
      name: 'list_api_keys',
      description: 'List all API keys for an agent. Only key prefixes are shown (full keys are not stored).',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID' },
          ...showUserProp,
        },
        required: ['chatbot_id'],
      },
      execute: async (params) => {
        const keys = await chatbotApi.listApiKeys(params.chatbot_id as string);
        if (params.show_user) navigate(`/agents/${params.chatbot_id}?section=overview`);
        if (keys.length === 0) return 'No API keys found for this agent.';
        return JSON.stringify(
          keys.map((k) => ({
            id: k.id,
            name: k.name,
            prefix: `${k.key_prefix}••••`,
            active: k.is_active,
            created: k.created_at,
          }))
        );
      },
    });

    // ---- revoke_api_key ----
    agent.registerTool({
      name: 'revoke_api_key',
      description: 'Revoke an API key for an agent. This is irreversible.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID' },
          key_id: { type: 'number', description: 'The API key ID to revoke' },
          ...showUserProp,
        },
        required: ['chatbot_id', 'key_id'],
      },
      execute: async (params) => {
        await chatbotApi.revokeApiKey(params.chatbot_id as string, params.key_id as number);
        if (params.show_user) navigate(`/agents/${params.chatbot_id}?section=overview`);
        return `Revoked API key ${params.key_id}.`;
      },
    });

    // ---- get_embed_code ----
    agent.registerTool({
      name: 'get_embed_code',
      description: 'Get the embed code snippet for adding the Flunkie widget to a website.',
      inputSchema: {
        type: 'object',
        properties: {
          chatbot_id: { type: 'string', description: 'The agent UUID' },
          format: {
            type: 'string',
            enum: ['script', 'npm', 'legacy'],
            description: 'Embed format: "script" (default), "npm", or "legacy"',
          },
          ...showUserProp,
        },
        required: ['chatbot_id'],
      },
      execute: async (params) => {
        const chatbot = await chatbotApi.getChatbot(params.chatbot_id as string);
        const publicId = chatbot.public_id;
        const format = (params.format as string) || 'script';
        const origin = window.location.origin;

        const snippets: Record<string, string> = {
          script: `<script src="${origin}/widget/flunkie.js"></script>\n<script>\n  Flunkie.initialize({\n    key: "YOUR_API_KEY",\n    chatbotId: "${publicId}"\n  });\n</script>`,
          npm: `npm install @flunkie/flunkie\n\nimport Flunkie from "@flunkie/flunkie";\n\nFlunkie.initialize({\n  key: "YOUR_API_KEY",\n  chatbotId: "${publicId}"\n});`,
          legacy: `<script\n  src="${origin}/widget/chatbot-widget.js"\n  data-chatbot-id="${publicId}"\n></script>`,
        };

        if (params.show_user) navigate(`/agents/${params.chatbot_id}?section=overview`);
        return (snippets[format] || snippets.script) as string;
      },
    });
  }

  return null;
}

export default DashboardAssistant;
